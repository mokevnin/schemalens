// Package ruledocs renders one Markdown page per registered rule, plus an
// index, from the rule registry. docs/rules is generated output: change a
// rule's Explain text, then run `mise run docs`.
package ruledocs

import (
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/mokevnin/schemalens/internal/rules"
)

// IndexName is the file name of the generated index page.
const IndexName = "README.md"

const banner = "<!-- Generated by `mise run docs` from the rule registry. Do not edit. -->\n\n"

// Render returns the generated pages keyed by file name.
func Render() (map[string]string, error) {
	pages := map[string]string{}
	all := rules.All()
	for _, r := range all {
		pages[r.ID+".md"] = page(r)
	}
	pages[IndexName] = index(all)
	return pages, nil
}

// Write renders the pages into dir, removing pages of rules that no longer exist.
func Write(dir string) error {
	pages, err := Render()
	if err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return err
	}
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if _, ok := pages[e.Name()]; !ok && strings.HasSuffix(e.Name(), ".md") {
			if err := os.Remove(filepath.Join(dir, e.Name())); err != nil {
				return err
			}
		}
	}
	for name, content := range pages {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			return err
		}
	}
	return nil
}

func dialects(r rules.Rule) string {
	ds := make([]string, len(r.Dialects))
	for i, d := range r.Dialects {
		ds[i] = string(d)
	}
	slices.Sort(ds)
	return strings.Join(ds, ", ")
}

func page(r rules.Rule) string {
	def := "on"
	if r.DefaultOff {
		def = "off (enable it under `rules` in schemalens.yml)"
	}
	var b strings.Builder
	b.WriteString(banner)
	fmt.Fprintf(&b, "# %s\n\n- Dialects: %s\n- Default: %s\n\n", r.ID, dialects(r), def)
	fmt.Fprintf(&b, "## Why\n\n%s\n\n## Fix\n\n%s\n\n## Exception\n\n%s\n\n", r.Explain.Why, r.Explain.Fix, r.Explain.Exception)
	fmt.Fprintf(&b, "The same text is printed by `schemalens explain %s`. An exclusion needs a written reason. Back to the [rule index](%s).\n", r.ID, IndexName)
	return b.String()
}

func index(all []rules.Rule) string {
	var b strings.Builder
	b.WriteString(banner)
	b.WriteString("# Rules\n\n| Rule | Dialects | Default |\n| --- | --- | --- |\n")
	for _, r := range all {
		def := "on"
		if r.DefaultOff {
			def = "off"
		}
		fmt.Fprintf(&b, "| [%s](%s.md) | %s | %s |\n", r.ID, r.ID, dialects(r), def)
	}
	return b.String()
}
